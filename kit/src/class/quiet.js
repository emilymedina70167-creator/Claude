// 不打扰（第十二轮，学生的要求 A-1：「老师一说话，页面就把我拉回板顶，打断我做题」）：
// 老师一轮写完以后页面要不要替学生滚、翻板。纯函数，课堂（classroom.js 的 finishTurn）问它。
//
// writing：学生正在写——输入框里有字、当前板上有没发的 Pencil 笔画、当前板上有写了没交的草稿，三样有一样就是；
// away：学生翻到了别的板在看。
// 两样有一样，页面就不动：老师新写的东西用输入条上方的一小条告诉学生（classroom.js 的 echo），学生点它才过去。
// 页面不动不等于不告诉：不滚的时候那一小条一定要出现，不能悄悄地什么都不发生。

/** 这一轮写完，页面能不能自己滚到新内容、翻到新板 */
export function shouldScroll({ writing = false, away = false } = {}) {
  return !writing && !away;
}
